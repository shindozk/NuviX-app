// Language detector
function detectLanguage(): string {
  try {
    const code = getLocales()[0]?.languageCode ?? 'en';
    // Map common language codes
    const normalizedCode = code.toLowerCase();
    if (normalizedCode === 'pt' || normalizedCode.startsWith('pt')) return 'pt';
    if (normalizedCode === 'es') return 'es';
    if (normalizedCode === 'de') return 'de';
    if (normalizedCode === 'fr') return 'fr';
    if (normalizedCode === 'it') return 'it';
    if (normalizedCode === 'nl') return 'nl';
    if (normalizedCode === 'pl') return 'pl';
    if (normalizedCode === 'ru') return 'ru';
    if (normalizedCode === 'uk') return 'uk';
    if (normalizedCode === 'zh' || normalizedCode === 'zh-cn') return 'zh';
    if (normalizedCode === 'zh-tw' || normalizedCode === 'zh-hk') return 'zh-TW';
    if (normalizedCode === 'ja') return 'ja';
    if (normalizedCode === 'ko') return 'ko';
    if (normalizedCode === 'tr') return 'tr';
    if (normalizedCode === 'ar') return 'ar';
    return 'en';
  } catch {
    return 'en';
  }
}

